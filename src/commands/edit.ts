import { BotContext } from "../types";
import {
  checkUserChatPermissions,
  convertRichBlocksToInput,
  escapeHtml,
  parseEditLink,
  processRichTemplate,
} from "../utils";
import { GrammyError } from "grammy";

export async function editCommand(ctx: BotContext): Promise<void> {
  const userId = ctx.from?.id;
  if (!userId || !ctx.chat) {
    return;
  }

  // 1. Reply validation: must reply to a message
  const replyMessage = ctx.message?.reply_to_message;
  if (!replyMessage) {
    await ctx.reply(
      `⚠️ <b>Missing Reply Target:</b>\n` +
        `Please reply to one of the bot's rendered messages with:\n` +
        `<code>/edit &lt;message-link&gt;</code>`,
      { parse_mode: "HTML" }
    );
    return;
  }

  // Ensure the message being replied to was generated by this bot (or user's own message)
  if (
    !replyMessage.from ||
    (replyMessage.from.id !== ctx.me.id && replyMessage.from.id !== userId)
  ) {
    await ctx.reply(
      `⚠️ <b>Invalid Message:</b>\n` +
        `You can only update using messages outputted by this bot. Please reply directly to one of the bot's rendered messages.`,
      { parse_mode: "HTML" }
    );
    return;
  }

  // 2. Parse command arguments: /edit <message-link> (e.g. https://t.me/channel/123 or https://t.me/c/1234567890/123)
  const rawTarget = typeof ctx.match === "string" ? ctx.match.trim() : "";
  const parsed = parseEditLink(rawTarget);

  if (!parsed) {
    await ctx.reply(
      `⚠️ <b>Message Link Required:</b>\n` +
        `Usage: <code>/edit &lt;message-link&gt;</code>\n\n` +
        `<b>Examples:</b>\n` +
        `• <code>/edit https://t.me/my_channel/123</code>\n` +
        `• <code>/edit https://t.me/c/1234567890/123</code> (private channel)\n` +
        `• <code>/edit @my_channel 123</code>\n\n` +
        `💡 <i>Tip: Right-click or long-press the post in your channel and tap <b>"Copy Link"</b>!</i>`,
      { parse_mode: "HTML" }
    );
    return;
  }

  const { targetChat, messageId: targetMessageId } = parsed;

  // 3. Dynamic Permission Check inside the target channel/chat
  const permission = await checkUserChatPermissions(
    ctx.api,
    targetChat,
    userId,
    "edit"
  );
  if (!permission.allowed) {
    await ctx.reply(
      `⛔ <b>Permission Denied in <code>${escapeHtml(targetChat)}</code>:</b>\n` +
        `${escapeHtml(
          permission.reason ||
            "You do not have permission to edit messages in this channel."
        )}`,
      { parse_mode: "HTML" }
    );
    return;
  }

  // 4. Update the target message with the replied message's content
  try {
    if ((replyMessage as any).rich_message) {
      const richMsg = (replyMessage as any).rich_message;
      const convertedBlocks = convertRichBlocksToInput(richMsg.blocks);
      const inputRichMsg: any = {
        blocks: convertedBlocks,
      };
      if (richMsg.is_rtl !== undefined) {
        inputRichMsg.is_rtl = richMsg.is_rtl;
      }

      await ctx.api.editMessageText(targetChat, targetMessageId, inputRichMsg);
    } else if (replyMessage.text) {
      if (replyMessage.from?.id !== ctx.me.id) {
        // Raw HTML from user's message
        const { html, isRtl, media } = processRichTemplate(replyMessage.text);
        await ctx.api.editMessageText(targetChat, targetMessageId, {
          html,
          media,
          is_rtl: isRtl,
        });
      } else {
        // Text message from bot: try text first, fallback to caption if media message
        try {
          await ctx.api.editMessageText(
            targetChat,
            targetMessageId,
            replyMessage.text,
            {
              entities: replyMessage.entities,
            }
          );
        } catch (textErr: any) {
          const desc =
            textErr instanceof GrammyError
              ? textErr.description
              : textErr?.message || "";
          if (desc.includes("there is no text in the message to edit")) {
            await ctx.api.editMessageCaption(targetChat, targetMessageId, {
              caption: replyMessage.text,
              caption_entities: replyMessage.entities,
            });
          } else {
            throw textErr;
          }
        }
      }
    } else if (replyMessage.caption) {
      // Caption message from bot: try caption first, fallback to text if text message
      try {
        await ctx.api.editMessageCaption(targetChat, targetMessageId, {
          caption: replyMessage.caption,
          caption_entities: replyMessage.caption_entities,
        });
      } catch (captionErr: any) {
        const desc =
          captionErr instanceof GrammyError
            ? captionErr.description
            : captionErr?.message || "";
        if (desc.includes("there is no caption in the message to edit")) {
          await ctx.api.editMessageText(
            targetChat,
            targetMessageId,
            replyMessage.caption,
            {
              entities: replyMessage.caption_entities,
            }
          );
        } else {
          throw captionErr;
        }
      }
    } else {
      await ctx.reply(
        `⚠️ <b>Unsupported Message Type:</b>\n` +
          `The replied message does not contain text or article content that can be edited.`,
        { parse_mode: "HTML" }
      );
      return;
    }

    await ctx.reply(
      `✅ <b>Success!</b> Message <code>#${targetMessageId}</code> in <code>${escapeHtml(
        targetChat
      )}</code> was updated with the new content.`,
      { parse_mode: "HTML" }
    );
  } catch (error: any) {
    const errorMsg =
      error instanceof GrammyError
        ? error.description
        : error?.message || "Unknown error";

    if (errorMsg.includes("message is not modified")) {
      await ctx.reply(
        `ℹ️ <b>Message Not Modified:</b>\n` +
          `The content of message <code>#${targetMessageId}</code> in <code>${escapeHtml(
            targetChat
          )}</code> is already identical to the replied message.`,
        { parse_mode: "HTML" }
      );
      return;
    }

    await ctx.reply(
      `❌ <b>Failed to update message in <code>${escapeHtml(targetChat)}</code>:</b>\n` +
        `<code>${escapeHtml(errorMsg)}</code>\n\n` +
        `💡 <b>Checklist:</b>\n` +
        `1. Make sure the bot is an <b>Administrator</b> in ${escapeHtml(
          targetChat
        )} with <b>Edit Messages</b> permission.\n` +
        `2. Ensure the message was originally sent by this bot (or the bot has rights to edit it).\n` +
        `3. Verify the message link and ID <code>#${targetMessageId}</code> are correct and the message was not deleted.`,
      { parse_mode: "HTML" }
    );
  }
}
