import { BotContext } from "../types";
import {
  checkUserChatPermissions,
  escapeHtml,
  normalizeTargetChat,
  parseTargetAndReply,
} from "../utils";
import { GrammyError } from "grammy";

export async function sendCommand(ctx: BotContext): Promise<void> {
  const userId = ctx.from?.id;
  if (!userId || !ctx.chat) {
    return;
  }

  // 1. Reply validation: must reply to an output message from this bot
  const replyMessage = ctx.message?.reply_to_message;
  if (!replyMessage) {
    await ctx.reply(
      `⚠️ <b>Missing Reply Target:</b>\n` +
        `Please reply to one of the bot's rendered messages with:\n` +
        `<code>/send &lt;channel_username_or_id&gt; [reply_to_id]</code>`,
      { parse_mode: "HTML" }
    );
    return;
  }

  // Ensure the message being replied to was generated by this bot
  if (!replyMessage.from || replyMessage.from.id !== ctx.me.id) {
    await ctx.reply(
      `⚠️ <b>Invalid Message:</b>\n` +
        `You can only forward messages outputted by this bot. Please reply directly to one of the bot's rendered messages.`,
      { parse_mode: "HTML" }
    );
    return;
  }

  // 2. Parse command arguments: /send @channel [post_link] OR /send https://t.me/channel/123
  const rawTarget = typeof ctx.match === "string" ? ctx.match.trim() : "";
  const parsed = parseTargetAndReply(rawTarget);

  let targetChat = parsed.target;
  let replyId = parsed.replyId;
  let replyChat = parsed.replyChat;

  // If target chat, replyId, or replyChat was not specified in the command, check if embedded inside the message
  const replyMsgText = (replyMessage as any).text || "";
  if (!replyId) {
    const anchorMatch = replyMsgText.match(/tg-reply-(\d+)/);
    if (anchorMatch) {
      replyId = parseInt(anchorMatch[1], 10);
    }
    const replyChatMatch = replyMsgText.match(/tg-reply-chat-([^"'\s>]+)/);
    if (replyChatMatch) {
      replyChat = decodeURIComponent(replyChatMatch[1]);
    }
  }

  if (!targetChat) {
    const chatAnchorMatch = replyMsgText.match(/tg-chat-([^"'\s>]+)/);
    if (chatAnchorMatch) {
      targetChat = decodeURIComponent(chatAnchorMatch[1]);
    }
  }

  if (!targetChat) {
    await ctx.reply(
      `⚠️ <b>Target Channel Required:</b>\n` +
        `Usage: <code>/send &lt;@channel_or_id&gt; [post_link]</code>\n\n` +
        `<b>Examples:</b>\n` +
        `• <code>/send @my_channel</code>\n` +
        `• <code>/send @my_channel https://t.me/my_channel/123</code>\n` +
        `• <code>/send @my_channel https://t.me/other_channel/123</code> (cross-channel reply)\n` +
        `• <code>/send https://t.me/my_channel/123</code> (direct post link)\n` +
        `• <code>/send -1001234567890</code> (private channel ID)\n\n` +
        `💡 <i>Tip: Forward any message from a private channel here to get its numeric Chat ID!</i>`,
      { parse_mode: "HTML" }
    );
    return;
  }

  targetChat = normalizeTargetChat(targetChat);

  // 3. Dynamic Permission Check inside the target channel/chat
  const permission = await checkUserChatPermissions(ctx.api, targetChat, userId);
  if (!permission.allowed) {
    await ctx.reply(
      `⛔ <b>Permission Denied in <code>${escapeHtml(targetChat)}</code>:</b>\n` +
        `${escapeHtml(
          permission.reason ||
            "You do not have permission to post messages in this channel."
        )}`,
      { parse_mode: "HTML" }
    );
    return;
  }

  // 4. Send without forward quoting using copyMessage (optionally in reply)
  try {
    const copyOptions: any = {};
    if (replyId) {
      const replyParams: any = {
        message_id: replyId,
      };

      // In Telegram Bot API 7.0+, replies across different channels/chats require chat_id
      if (replyChat && replyChat !== targetChat) {
        replyParams.chat_id = replyChat;
      } else {
        replyParams.allow_sending_without_reply = true;
      }

      copyOptions.reply_parameters = replyParams;
    }

    await ctx.api.copyMessage(
      targetChat,
      ctx.chat.id,
      replyMessage.message_id,
      copyOptions
    );

    const replyFrom =
      replyChat && replyChat !== targetChat
        ? ` from <code>${escapeHtml(replyChat)}</code>`
        : "";
    const replyNote = replyId
      ? ` as a reply to message <code>#${replyId}</code>${replyFrom}`
      : "";

    await ctx.reply(
      `✅ <b>Success!</b> The message was sent to <code>${escapeHtml(
        targetChat
      )}</code>${replyNote} without forward tags.`,
      { parse_mode: "HTML" }
    );
  } catch (error: any) {
    const errorMsg =
      error instanceof GrammyError
        ? error.description
        : error?.message || "Unknown error";

    await ctx.reply(
      `❌ <b>Failed to send to <code>${escapeHtml(targetChat)}</code>:</b>\n` +
        `<code>${escapeHtml(errorMsg)}</code>\n\n` +
        `💡 <b>Checklist:</b>\n` +
        `1. Make sure the bot is added as an <b>Administrator</b> in ${escapeHtml(
          targetChat
        )}.\n` +
        `2. Ensure the bot has permission to <b>Post Messages</b>.\n` +
        `3. Verify the channel username or numeric ID (e.g. <code>-100...</code>) is correct.`,
      { parse_mode: "HTML" }
    );
  }
}
